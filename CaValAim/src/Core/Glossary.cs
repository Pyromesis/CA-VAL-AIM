    public static IReadOnlyList<GlossaryTerm> Search(string? query)
    {
        string q = (query ?? "").Trim();
        if (q.Length == 0) return All;
        return All.Where(t =>
            t.Term.Contains(q, StringComparison.OrdinalIgnoreCase) ||
            t.Es.Contains(q, StringComparison.OrdinalIgnoreCase) ||
            t.En.Contains(q, StringComparison.OrdinalIgnoreCase)).ToList();
    }
